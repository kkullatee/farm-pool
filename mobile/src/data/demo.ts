export function coordinatesFor(location: string): Coordinates {
  const normalized = location.trim().toLowerCase();
  const match = knownLocations.find(([key]) => normalized.includes(key));
  return match?.[1] ?? { latitude: -17.05, longitude: 145.55 };
}
